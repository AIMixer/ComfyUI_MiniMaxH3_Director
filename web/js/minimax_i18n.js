let _locale = null;
const _listeners = new Set();

function detectDefaultLocale() {
    try {
        const nav = (typeof navigator !== "undefined" && (navigator.language || navigator.userLanguage)) || "zh";
        return String(nav).toLowerCase().startsWith("zh") ? "zh" : "en";
    } catch {
        return "zh";
    }
}

export function getLocale() {
    if (_locale) return _locale;
    try {
        const saved = localStorage.getItem(LOCALE_STORAGE_KEY);
        if (saved === "zh" || saved === "en") {
            _locale = saved;
            return _locale;
        }
    } catch { /* ignore */ }
    _locale = detectDefaultLocale();
    return _locale;
}

export function setLocale(lang) {
    const next = lang === "en" ? "en" : "zh";
    if (_locale === next) return _locale;
    _locale = next;
    try {
        localStorage.setItem(LOCALE_STORAGE_KEY, next);
    } catch { /* ignore */ }
    for (const fn of _listeners) {
        try { fn(next); } catch { /* ignore */ }
    }
    return _locale;
}

export function toggleLocale() {
    return setLocale(getLocale() === "zh" ? "en" : "zh");
}

export function onLocaleChange(fn) {
    if (typeof fn === "function") _listeners.add(fn);
    return () => _listeners.delete(fn);
}

function formatTemplate(str, vars) {
    if (!vars) return str;
    return String(str).replace(/\{(\w+)\}/g, (_, k) => (
        vars[k] != null ? String(vars[k]) : `{${k}}`
    ));
}

export function t(key, vars) {
    const locale = getLocale();
    const dict = DICTS[locale] || ZH;
    const raw = dict[key] ?? ZH[key] ?? key;
    return formatTemplate(raw, vars);
}

/** Apply data-i18n / data-i18n-title / data-i18n-placeholder / data-i18n-html on a subtree. */
export function applyI18nDom(root) {
    if (!root?.querySelectorAll) return;
    for (const el of root.querySelectorAll("[data-i18n]")) {
        const key = el.getAttribute("data-i18n");
        if (key) el.textContent = t(key);
    }
    for (const el of root.querySelectorAll("[data-i18n-html]")) {
        const key = el.getAttribute("data-i18n-html");
        if (key) el.innerHTML = t(key);
    }
    for (const el of root.querySelectorAll("[data-i18n-title]")) {
        const key = el.getAttribute("data-i18n-title");
        if (key) el.title = t(key);
    }
    for (const el of root.querySelectorAll("[data-i18n-placeholder]")) {
        const key = el.getAttribute("data-i18n-placeholder");
        if (key) el.placeholder = t(key);
    }
}

export function taskDisplayLabel(taskKey) {
    const key = String(taskKey || "").trim();
    const labelKey = `task.${key}`;
    if (ZH[labelKey] || EN[labelKey]) {
        return t("task.option", { key, label: t(labelKey) });
    }
    return key;
}

export function aspectDisplayLabel(storageLabel) {
    const key = ASPECT_I18N_KEYS[storageLabel];
    return key ? t(key) : String(storageLabel || "");
}
